import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { rootTokens, darkTokens, compactTokens } from '../config/tokens.mjs';
import { breakpoints, utilities, responsiveUtilities } from '../config/utilities.mjs';

const root = resolve(import.meta.dirname, '..');
const outputs = {
  tokens: resolve(root, 'packages/core/src/tokens/tokens.css'),
  utilities: resolve(root, 'packages/core/src/utilities/utilities.css'),
};
const normalizeLineEndings = (content) => content.replace(/\r\n/g, '\n');
const declarations = (tokens) => Object.entries(tokens).map(([name,value]) => `--nx-${name}:${value}`).join(';');
const rule = (name, body, prefix = '') => `.${prefix ? `${prefix}\\:` : ''}nx-${name}{${body}}`;

export function renderTokens() {
  const dark = declarations(darkTokens);
  return `/* Generated by scripts/generate-css.mjs. Do not edit directly. */\n@layer nx-base {\n  :root {color-scheme:light;${declarations(rootTokens)}}\n  [data-nx-theme="dark"] {color-scheme:dark;${dark}}\n  [data-nx-density="compact"] {${declarations(compactTokens)}}\n  @media (prefers-color-scheme:dark) { [data-nx-theme="system"] {color-scheme:dark;${dark}} }\n}\n`;
}

export function renderUtilities() {
  const byName = new Map(utilities);
  const base = utilities.map(([name,body]) => rule(name, body)).join('');
  const responsive = Object.entries(responsiveUtilities).map(([prefix,names]) => {
    const rules = names.map((name) => rule(name, byName.get(name), prefix)).join('');
    return `@media(min-width:${breakpoints[prefix]}){${rules}}`;
  }).join('');
  return `/* Generated by scripts/generate-css.mjs. Do not edit directly. */\n@layer nx-utilities {${base}${responsive}}\n`;
}

export async function generateCss({ check = false } = {}) {
  const expected = [[outputs.tokens, renderTokens()], [outputs.utilities, renderUtilities()]];
  if (check) {
    const stale = [];
    for (const [path, content] of expected) {
      const current = normalizeLineEndings(await readFile(path, 'utf8'));
      if (current !== normalizeLineEndings(content)) stale.push(path);
    }
    if (stale.length) throw new Error(`Generated CSS is stale:\n${stale.map((path) => `- ${path}`).join('\n')}\nRun: corepack pnpm generate:css`);
    return;
  }
  await Promise.all(expected.map(([path, content]) => writeFile(path, content)));
}

const invokedPath = process.argv[1] ? fileURLToPath(new URL(import.meta.url)) === resolve(process.argv[1]) : false;
if (invokedPath) {
  await generateCss({ check: process.argv.includes('--check') });
  console.log(process.argv.includes('--check') ? 'Generated CSS is current.' : 'Generated token and utility CSS.');
}
